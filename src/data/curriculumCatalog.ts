export function buildQuiz(params: {
  id: string;
  subject: string;
  title?: string;
  description: string;
  department: DepartmentName | 'تربوي مشترك';
  courseCategory: 'specialized' | 'pedagogical';
  academicYear: AcademicYearName;
  teacherName: string;
  durationMinutes?: number;
  questions: Question[];
}): Quiz {
  return {
    id: params.id,
    title: params.title ?? `اختبار مادة: ${params.subject}`,
    description: params.description,
    subject: params.subject,
    department: params.department,
    courseCategory: params.courseCategory,
    teacherName: params.teacherName,
    academicYear: params.academicYear,
    durationMinutes: params.durationMinutes ?? 15,
    createdAt: '2026-11-20',
    isActive: true,
    questions: params.questions,
  };
}

